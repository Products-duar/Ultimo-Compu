    private void GuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_GuardarActionPerformed
        // TODO add your handling code here:
        int fila = JDatos.getSelectedRow();

    if (fila == -1) {

        javax.swing.JOptionPane.showMessageDialog(
            this, "Seleccione un producto de la tabla."
        );
        return;
    }

    try {

        String codigo = Codigo.getText().trim();
        String producto = Producto.getText().trim();
        String membresia = Membresía.getSelectedItem().toString();

        if (codigo.isEmpty() || producto.isEmpty()
                || Cantidad.getText().trim().isEmpty()
                || PrecioB.getText().trim().isEmpty()
                || Membresía.getSelectedIndex() == 0) {

            javax.swing.JOptionPane.showMessageDialog(
                this, "Complete todos los campos."
            );
            return;
        }

        int cantidad = Integer.parseInt(Cantidad.getText());
        double precio = Double.parseDouble(PrecioB.getText());

        if (cantidad <= 0 || precio <= 0) {

            javax.swing.JOptionPane.showMessageDialog(
                this, "La cantidad y el precio deben ser mayores que cero."
            );
            return;
        }

        double porcentaje = 0;

        if (membresia.equals("Plata 10%")) {
            porcentaje = 0.10;
        } else if (membresia.equals("Oro 20%")) {
            porcentaje = 0.20;
        }

        double montoOriginal = cantidad * precio;
        double descuento = montoOriginal * porcentaje;
        double montoFinal = montoOriginal - descuento;

        javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel) JDatos.getModel();

        modelo.setValueAt(codigo, fila, 0);
        modelo.setValueAt(producto, fila, 1);
        modelo.setValueAt(cantidad, fila, 2);
        modelo.setValueAt(precio, fila, 3);
        modelo.setValueAt(membresia, fila, 4);
        modelo.setValueAt(descuento, fila, 5);
        modelo.setValueAt(montoFinal, fila, 6);

        limpiarCampos();

        javax.swing.JOptionPane.showMessageDialog(
            this, "Cambios guardados correctamente."
        );

    } catch (NumberFormatException e) {

        javax.swing.JOptionPane.showMessageDialog(
            this, "Ingrese datos numéricos válidos."
        );
    }
    }//GEN-LAST:event_GuardarActionPerformed

