    private void cargarDatos() {
        int fila = JDatos.getSelectedRow();
        
        if (fila >= 0) {
            javax.swing.table.DefaultTableModel modelo =
                (javax.swing.table.DefaultTableModel) JDatos.getModel();
        
            Nombre.setText(modelo.getValueAt(fila, 0).toString());
            Categoría.setSelectedItem(modelo.getValueAt(fila, 1));
            PrecioU.setText(modelo.getValueAt(fila, 2).toString());
            Cantidad.setText(modelo.getValueAt(fila, 3).toString());
    }
    }

    private void limpiarCampos() {
        Nombre.setText("");
        Categoría.setSelectedIndex(0);
        PrecioU.setText("");
        Cantidad.setText("");
        JDatos.clearSelection();
    }
