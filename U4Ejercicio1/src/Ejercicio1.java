    private void GuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_GuardarActionPerformed
        // TODO add your handling code here:
        int fila = JDatos.getSelectedRow();

    if (fila == -1) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Seleccione una factura de la tabla."
        );
        return;
    }

    try {
        String cliente = Nombre.getText().trim();
        String categoria = Categoría.getSelectedItem().toString();

        double precio = Double.parseDouble(PrecioU.getText());
        int cantidad = Integer.parseInt(Cantidad.getText());

        if (cliente.isEmpty() || categoria.equals("Seleccionar")) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Complete todos los campos."
            );
            return;
        }

        if (precio <= 0 || cantidad <= 0) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "El precio y la cantidad deben ser mayores que cero."
            );
            return;
        }

        double subtotal = precio * cantidad;
        double iva = subtotal * 0.13;
        double total = subtotal + iva;

        javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel) JDatos.getModel();

        modelo.setValueAt(cliente, fila, 0);
        modelo.setValueAt(categoria, fila, 1);
        modelo.setValueAt(precio, fila, 2);
        modelo.setValueAt(cantidad, fila, 3);
        modelo.setValueAt(subtotal, fila, 4);
        modelo.setValueAt(iva, fila, 5);
        modelo.setValueAt(total, fila, 6);

        limpiarCampos();

        javax.swing.JOptionPane.showMessageDialog(
            this, "Cambios guardados correctamente."
        );

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Ingrese datos numéricos válidos."
        );
    }
    }//GEN-LAST:event_GuardarActionPerformed

