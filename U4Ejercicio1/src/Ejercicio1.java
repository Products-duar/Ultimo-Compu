    private void FacturaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_FacturaActionPerformed
        // TODO add your handling code here:
        try {
        String cliente = Nombre.getText().trim();
        String categoria = Categoría.getSelectedItem().toString();

        double precio = Double.parseDouble(PrecioU.getText());
        int cantidad = Integer.parseInt(Cantidad.getText());

        if (cliente.isEmpty() || categoria.equals("Seleccionar")) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "Complete todos los campos."
            );
            return;
        }

        if (precio <= 0 || cantidad <= 0) {
            javax.swing.JOptionPane.showMessageDialog(
                this, "El precio y la cantidad deben ser mayores que cero."
            );
            return;
        }

        double subtotal = precio * cantidad;
        double iva = subtotal * 0.13;
        double total = subtotal + iva;

        javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel) JDatos.getModel();

        modelo.addRow(new Object[]{
            cliente,
            categoria,
            precio,
            cantidad,
            subtotal,
            iva,
            total
        });

        limpiarCampos();

        javax.swing.JOptionPane.showMessageDialog(
            this, "Factura agregada correctamente."
        );

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Ingrese un precio y una cantidad válidos."
        );
        }
    }//GEN-LAST:event_FacturaActionPerformed

    private void EliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_EliminarActionPerformed
        // TODO add your handling code here:
        int fila = JDatos.getSelectedRow();

    if (fila == -1) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Seleccione una factura para eliminar."
        );
        return;
    }

    int respuesta = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "¿Está seguro de eliminar este registro?",
        "Confirmar eliminación",
        javax.swing.JOptionPane.YES_NO_OPTION
    );

    if (respuesta == javax.swing.JOptionPane.YES_OPTION) {

        javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel) JDatos.getModel();

        modelo.removeRow(fila);

        limpiarCampos();

        javax.swing.JOptionPane.showMessageDialog(
            this, "Registro eliminado correctamente."
        );
    }
    }//GEN-LAST:event_EliminarActionPerformed

