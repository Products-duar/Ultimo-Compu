    private void jbtnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtnEliminarActionPerformed
        // TODO add your handling code here:
        if (modelo.getRowCount() <= 0) {
    JOptionPane.showMessageDialog(null, "No hay registros!!!");
    } else {
    modelo.removeRow(jtabDatos.getSelectedRow());
    JOptionPane.showMessageDialog(null, "Registro Eliminado!!!");
    limpiarCajas();
    }
    }//GEN-LAST:event_jbtnEliminarActionPerformed

    private void jbtnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtnEditarActionPerformed
        int filaSeleccionada = jtabDatos.getSelectedRow();

    if (filaSeleccionada == -1) {
        JOptionPane.showMessageDialog(null, "Debe seleccionar un registro de la tabla para editar");
        return;
    }

    modelo.setValueAt(jtxtDpi.getText(), filaSeleccionada, 0);
    modelo.setValueAt(jtxtNombre.getText(), filaSeleccionada, 1);
    modelo.setValueAt(jtxtApellidos.getText(), filaSeleccionada, 2);
    modelo.setValueAt(jtxtSalario.getText(), filaSeleccionada, 3);
    modelo.setValueAt(jcbxCategoria.getSelectedItem(), filaSeleccionada, 4);
    modelo.setValueAt(jcbxPuesto.getSelectedItem(), filaSeleccionada, 5);

    // Recalcular el salario total y actualizar la columna TOTAL (índice 6)
    totalSalario();
    modelo.setValueAt(total, filaSeleccionada, 6);

    // Limpiar cajas
    limpiarCajas();
    }//GEN-LAST:event_jbtnEditarActionPerformed

    private void jbtnInsertarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtnInsertarActionPerformed
        // TODO add your handling code here:
        totalSalario();
        
        modelo.addRow(new Object[]
    {
        jtxtDpi.getText(),
        jtxtNombre.getText(),
        jtxtApellidos.getText(),
        jtxtSalario.getText(),
        jcbxCategoria.getSelectedItem(),
        jcbxPuesto.getSelectedItem(),
        total
    });
    limpiarCajas();
    }
    public void totalSalario()
       {
    salario=Double.parseDouble(jtxtSalario.getText());

    if(jcbxCategoria.getSelectedItem().equals("A"))
        total=salario+CatA;
    else if(jcbxCategoria.getSelectedItem().equals("B"))
        total=salario+CatB;
    else if(jcbxCategoria.getSelectedItem().equals("C"))
        total=salario+CatC;
    else
        total=salario;
    } 
    
    public void limpiarCajas ()
    {
        jtxtDpi.setText("");
        jtxtNombre.setText("");
        jtxtApellidos.setText("");
        jtxtSalario.setText("");
        jcbxCategoria.setSelectedIndex(0);
        jcbxPuesto.setSelectedIndex(0);
        jtxtDpi.requestFocus();
    }//GEN-LAST:event_jbtnInsertarActionPerformed

    private void jbtnImprimirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jbtnImprimirActionPerformed
        // TODO add your handling code here:
        MessageFormat Header = new MessageFormat("Planilla 2025"); // Importar librería
MessageFormat footer = new MessageFormat("Página {0}");

try {
    PrintRequestAttributeSet set = new HashPrintRequestAttributeSet(); // Importar librería
    set.add(OrientationRequested.LANDSCAPE); // Importar librería
    jtabDatos.print(JTable.PrintMode.FIT_WIDTH, Header, footer, true, set, true);
    JOptionPane.showMessageDialog(null, "\nImpreso con éxito");
} catch (java.awt.print.PrinterException e) {
    JOptionPane.showMessageDialog(null, "\nFallido\n" + e);
}
    }//GEN-LAST:event_jbtnImprimirActionPerformed

